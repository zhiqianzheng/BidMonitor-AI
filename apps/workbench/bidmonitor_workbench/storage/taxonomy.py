def suggest_category(title):
    if re.search("监理|咨询|设计|勘察|审计|租赁|物业|保洁|培训|服务|劳务", title):
        return "服务"
    if re.search("设备|仪器|药品|耗材|家具|材料|物资|办公用品|器械|采购无人机|无人机采购", title):
        return "货物"
    if re.search("施工|装修|改造|建设工程|修缮|道路工程|土建", title):
        return "工程"
    return "待分类"


